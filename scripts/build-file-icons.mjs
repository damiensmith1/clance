#!/usr/bin/env node
// Copies a curated subset of Material Icon Theme's file and folder icons
// (MIT, github.com/material-extensions/vscode-material-icon-theme) into
// src/shared/vendor/file-icons/, with a map trimmed to just those icons. The
// full set is ~1,250 SVGs and 5 MB; the Files tree needs the common ones.
// Which icon a name gets is the theme's own manifest, not ours — the lists
// below only choose which names are worth shipping. Rerun after changing them
// or the pinned material-icon-theme version.

import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const ROOT = new URL("..", import.meta.url).pathname;
const PKG = dirname(require.resolve("material-icon-theme/package.json"));
const OUT = join(ROOT, "src/shared/vendor/file-icons");
const manifest = JSON.parse(readFileSync(join(PKG, "dist/material-icons.json"), "utf8"));

const EXTENSIONS = `ts tsx mts cts d.ts test.ts spec.ts js jsx mjs cjs test.js spec.js json jsonc json5 md mdx txt
  env yml yaml toml ini conf cfg lock py pyi ipynb rb go mod rs swift java kt kts scala c h cpp cc hpp cs php lua
  r dart ex exs erl hs clj elm zig nim html htm css scss sass less styl svg png jpg jpeg gif webp ico bmp avif
  sh bash zsh fish ps1 bat sql db sqlite xml csv tsv log pdf zip gz tgz tar 7z rar dmg vue svelte astro graphql gql
  prisma proto wasm mp4 mov webm mp3 wav ogg ttf otf woff woff2 map patch diff plist node pem key crt tf
  hcl nix vim editorconfig http rest ejs hbs pug liquid tex bib rst adoc`
  .split(/\s+/).filter(Boolean);

const FILE_NAMES = `package.json package-lock.json yarn.lock pnpm-lock.yaml pnpm-workspace.yaml bun.lockb tsconfig.json
  jsconfig.json .gitignore .gitattributes .gitmodules .gitkeep license license.md license.txt readme.md changelog.md
  contributing.md security.md code_of_conduct.md dockerfile docker-compose.yml docker-compose.yaml compose.yml .dockerignore
  makefile .env .env.local .env.example .env.development .env.production .editorconfig .prettierrc .prettierrc.json
  .prettierignore .eslintrc .eslintrc.json .eslintrc.js eslint.config.js eslint.config.mjs .nvmrc .node-version .npmrc
  vite.config.ts vite.config.js webpack.config.js rollup.config.js tailwind.config.js tailwind.config.ts postcss.config.js
  next.config.js next.config.mjs babel.config.js .babelrc jest.config.js jest.config.ts vitest.config.ts playwright.config.ts
  cargo.toml cargo.lock go.mod go.sum requirements.txt pyproject.toml poetry.lock pipfile gemfile gemfile.lock
  procfile vercel.json netlify.toml .mcp.json favicon.ico robots.txt manifest.json electron-builder.yml`
  .split(/\s+/).filter(Boolean);

const FOLDER_NAMES = `src source lib docs doc scripts script dist build out release node_modules .github .vscode .claude
  .git test tests __tests__ spec e2e public static assets images img icons components pages app api config configs
  utils util helpers hooks styles css server client packages vendor types typings shared core bin tools
  coverage fonts locales i18n android ios migrations database db models services routes views templates layouts
  middleware plugins mocks fixtures examples docker .husky logs tmp temp cache backup data prisma`
  .split(/\s+/).filter(Boolean);

// Names the theme maps somewhere this app would rather be specific about.
const OVERRIDES = { fileNames: { "claude.md": "claude", "agents.md": "markdown" } };

const used = new Set([manifest.file, manifest.folder, manifest.folderExpanded]);
const map = {
  file: manifest.file,
  folder: manifest.folder,
  folderExpanded: manifest.folderExpanded,
  fileExtensions: {},
  fileNames: {},
  folderNames: {},
  folderNamesExpanded: {},
};
function take(table, source, keys) {
  for (const key of keys) {
    const icon = source[key];
    if (!icon || !manifest.iconDefinitions[icon]) continue;
    map[table][key] = icon;
    used.add(icon);
  }
}
take("fileExtensions", manifest.fileExtensions, EXTENSIONS);
take("fileNames", manifest.fileNames, FILE_NAMES);
take("folderNames", manifest.folderNames, FOLDER_NAMES);
take("folderNamesExpanded", manifest.folderNamesExpanded, FOLDER_NAMES);
for (const [name, icon] of Object.entries(OVERRIDES.fileNames)) {
  if (!manifest.iconDefinitions[icon]) continue;
  map.fileNames[name] = icon;
  used.add(icon);
}

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });
for (const icon of used) {
  const source = join(PKG, "dist", manifest.iconDefinitions[icon].iconPath);
  copyFileSync(source, join(OUT, `${icon}.svg`));
}
// A module rather than JSON: the renderer imports it, and can't fetch a file:// URL.
writeFileSync(join(OUT, "map.js"), `// Generated by scripts/build-file-icons.mjs. Do not edit.\nexport default ${JSON.stringify(map)};\n`);
copyFileSync(join(PKG, "LICENSE"), join(OUT, "LICENSE"));
console.log(`wrote ${used.size} icons to src/shared/vendor/file-icons`);
